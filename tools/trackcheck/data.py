def timing_selftest(tol=0.05, verbose=False):
    """自检：`《僵尸时间表》` vs 模型。

    返回 {'cols': [...超差项], 'abs': [...]}：
      · `cols` 每列耗时的相对误差（> tol 才列）
      · `abs`  绝对时刻的相对误差（9/5 列各算一次，> tol 才列）
    """
    cols, abss = [], []
    for key, kind in _TIMING_KIND.items():
        tbl = timing_cs_per_col(key)
        got = WALK_CS.get(kind)
        if tbl is None or got is None:
            cols.append((key, kind, tbl, got, None))
            continue
        err = abs(got - tbl) / tbl
        if verbose or err > tol:
            cols.append((key, kind, round(tbl, 1), got, round(err, 3)))
    for kind, row in TIMING_PLAIN.items():
        if kind not in V_WALK:
            continue
        for i, col in enumerate((9, 5)):
            if (kind, col) in _TIMING_ABS_SKIP:
                continue
            want = row[i if i == 0 else 4]
            got = timing_model_time(kind, col)
            err = abs(got - want) / want
            if verbose or err > tol:
                abss.append((kind, col, want, round(got), round(err, 3)))
    return dict(cols=cols, abs=abss)

