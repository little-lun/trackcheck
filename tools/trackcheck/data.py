# 表里 9 列那一项是"固定时刻"（还没开始走）的类型 → 求差时跳过第一段
_TIMING_SKIP0 = {'潜水啃食'}


def timing_cs_per_col(key):
    """表里这一行 → 每列走多少 cs（相邻列间隔的均值）。

    ★ 只有 5 项都有的行才算，缺项的直接返回 None（不猜）。
    """
    row = TIMING_PUMPKIN.get(key)
    if not row or len(row) < 2:
        return None
    vals = list(row)
    if key in _TIMING_SKIP0:
        vals = vals[1:]
    diffs = [vals[i] - vals[i - 1] for i in range(1, len(vals))]
    diffs = [d for d in diffs if d > 0]
    return sum(diffs) / float(len(diffs)) if diffs else None


