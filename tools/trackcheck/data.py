def avg_speed(name, v=None):
    """返回 px/cs。v 不给就取速度区间中值。

    ★ 2026-10-23：**表优先**。`《僵尸时间表》` 给了"到第 N 列植物要多少 cs"，
      直接用 `V_WALK[name]` 反算的速度，比"速度参数 × SPEED_K × (n+1)/n"准得多
      （后者对慢速档系统性偏慢 20%+）。表里没有的类型仍走旧公式。
      v 仍然按区间抽，用来给个体留一点差异（表只给平均值）。
    """
    hp, vmin, vmax, uniform, n = ZOMB[name][:5]
    if v is None:
        v = (vmin + vmax) / 2
    rng_cs = WALK_CS_RANGE.get(name)
    if rng_cs:
        # 巨人类：速度随机区间由表直接给出（420~590cs/列）
        cs = (rng_cs[0] + rng_cs[1]) / 2.0
        return CELL_W / cs
    eff = V_WALK.get(name)
    if eff is not None:
        mid = (vmin + vmax) / 2.0
        return eff * (v / mid) if mid else eff
    if uniform:
        return v
    return v * SPEED_K * (n + 1) / n


